CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(254) NOT NULL,
    email VARCHAR(254) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('ADMIN', 'MEMBER', 'VIEWER')),
    demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX ux_app_users_username ON app_users (lower(username));
CREATE UNIQUE INDEX ux_app_users_email ON app_users (lower(email));

-- Unowned rows belong to the local development profile. On the first cloud
-- startup, the administrator adopts the records created before accounts existed.
ALTER TABLE employees ADD COLUMN owner_id BIGINT REFERENCES app_users(id);
DROP INDEX ux_employees_email;
CREATE UNIQUE INDEX ux_employees_email ON employees (COALESCE(owner_id, 0), lower(email));
CREATE INDEX ix_employees_owner_name ON employees (owner_id, full_name, id);
