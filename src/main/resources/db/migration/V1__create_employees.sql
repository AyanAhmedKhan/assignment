CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL CHECK (length(trim(full_name)) > 0),
    email VARCHAR(254) NOT NULL CHECK (length(trim(email)) > 0),
    phone_number VARCHAR(32) NOT NULL,
    department VARCHAR(32) NOT NULL CHECK (department IN
        ('ENGINEERING', 'PRODUCT', 'DESIGN', 'OPERATIONS', 'HUMAN_RESOURCES', 'FINANCE')),
    designation VARCHAR(120) NOT NULL CHECK (length(trim(designation)) > 0),
    date_of_joining DATE NOT NULL,
    salary NUMERIC(12, 2) NOT NULL CHECK (salary >= 0),
    status VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE')),
    version BIGINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX ux_employees_email ON employees (lower(email));
CREATE INDEX ix_employees_department_status ON employees (department, status);
CREATE INDEX ix_employees_full_name_id ON employees (full_name, id);
